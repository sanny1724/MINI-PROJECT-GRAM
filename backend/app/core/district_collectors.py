def get_district_collector(district_name: str):
    if not district_name:
        return TELANGANA_DISTRICT_COLLECTORS[15] # Default Medak

    raw_key = district_name.strip().lower()
    normalized_key = DISTRICT_ALIASES.get(raw_key, raw_key)

    for c in TELANGANA_DISTRICT_COLLECTORS:
        c_key = c["district"].strip().lower()
        if c_key == normalized_key or c_key in raw_key or raw_key in c_key:
            return c

    return {
        "district": district_name,
        "name": "Sri. District Collector, IAS",
        "designation": "District Collector & District Magistrate",
        "cadre": "IAS",
        "phone": "040-23454000",
        "email": f"collector-{raw_key.replace(' ', '')}@telangana.gov.in",
        "portalUrl": "https://www.telangana.gov.in/contacts/district-officials/"
    }

