/**
 * Get District Collector by district name (case-insensitive with alias fallback)
 */
export function getDistrictCollector(districtName) {
  if (!districtName) {
    return TELANGANA_DISTRICT_COLLECTORS[15]; // Default Medak
  }

  const rawKey = districtName.trim().toLowerCase();
  const normalizedKey = DISTRICT_ALIASES[rawKey] || rawKey;

  const found = TELANGANA_DISTRICT_COLLECTORS.find(c => {
    const cKey = c.district.trim().toLowerCase();
    return cKey === normalizedKey || cKey.includes(rawKey) || rawKey.includes(cKey);
  });

  return found || {
    district: districtName,
    name: "Sri. District Collector, IAS",
    designation: "District Collector & District Magistrate",
    cadre: "IAS",
    phone: "040-23454000",
    email: `collector-${rawKey.replace(/\s+/g, '')}@telangana.gov.in`,
    portalUrl: "https://www.telangana.gov.in/contacts/district-officials/"
  };
}
